#!/bin/sh
# Print the Homebrew formula for a published release. The tap lives in
# https://github.com/mcaney006/homebrew-zigmap (Formula/zigmap.rb).
#   sh packaging/homebrew/render-formula.sh v0.2.0 [SHA256SUMS] > Formula/zigmap.rb
# Without a SHA256SUMS path, the release's own file is downloaded.
set -eu
TAG=${1:?usage: render-formula.sh TAG [SHA256SUMS]}
case $TAG in v*) ;; *) TAG="v$TAG" ;; esac
VERSION=${TAG#v}
BASE="https://github.com/mcaney006/ZigMap/releases/download/$TAG"
if [ $# -ge 2 ]; then
	SUMS=$(cat "$2")
else
	SUMS=$(curl -fsSL "$BASE/SHA256SUMS")
fi
sum() {
	s=$(printf '%s\n' "$SUMS" | awk -v f="zigmap-$1.tar.gz" '$2 == f { print $1 }')
	[ -n "$s" ] || { echo "zigmap-$1.tar.gz missing from SHA256SUMS" >&2; exit 1; }
	printf '%s' "$s"
}
AM=$(sum aarch64-macos)
XM=$(sum x86_64-macos)
AL=$(sum aarch64-linux)
XL=$(sum x86_64-linux)

cat <<EOF
# typed: strict
# frozen_string_literal: true

# Generated by packaging/homebrew/render-formula.sh in mcaney006/ZigMap.
class Zigmap < Formula
  desc "Network scanner written in Zig, without libpcap"
  homepage "https://github.com/mcaney006/ZigMap"
  version "$VERSION"

  on_macos do
    on_arm do
      url "$BASE/zigmap-aarch64-macos.tar.gz"
      sha256 "$AM"
    end
    on_intel do
      url "$BASE/zigmap-x86_64-macos.tar.gz"
      sha256 "$XM"
    end
  end

  on_linux do
    on_arm do
      url "$BASE/zigmap-aarch64-linux.tar.gz"
      sha256 "$AL"
    end
    on_intel do
      url "$BASE/zigmap-x86_64-linux.tar.gz"
      sha256 "$XL"
    end
  end

  def install
    bin.install "zigmap"
  end

  def caveats
    <<~TEXT
      -sT (connect scan) needs no privileges. -sS and -sU work on Linux only
      and need root or CAP_NET_RAW. Only scan hosts you are authorized to scan.
    TEXT
  end

  test do
    assert_match "zigmap #{version} ", shell_output("#{bin}/zigmap --version")
    # A dry run lists the targets and sends nothing.
    assert_match "No packets were sent.", shell_output("#{bin}/zigmap --dry-run -p 80 127.0.0.1")
  end
end
EOF
